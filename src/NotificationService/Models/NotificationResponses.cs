/// <summary>
/// Response for the service's health check
/// </summary>
public class NotificationHealthResponse
{
    /// <summary>
    /// Overall service status
    /// </summary>
    public bool IsHealthy { get; set; }

    /// <summary>
    /// Service version
    /// </summary>
    public required string Version { get; set; }

    /// <summary>
    /// Check timestamp
    /// </summary>
    public DateTime Timestamp { get; set; } = DateTime.UtcNow;

    /// <summary>
    /// Status of external providers
    /// </summary>
    public Dictionary<string, ProviderHealth> Providers { get; set; } = new();

    /// <summary>
    /// Database status
    /// </summary>
    public bool DatabaseHealthy { get; set; }

    /// <summary>
    /// Redis cache status
    /// </summary>
    public bool CacheHealthy { get; set; }

    /// <summary>
    /// Queued notifications
    /// </summary>
    public int QueuedNotifications { get; set; }

    /// <summary>
    /// Jobs being processed
    /// </summary>
    public int ProcessingJobs { get; set; }
}

/// <summary>
/// Status of a notification provider
/// </summary>
public class ProviderHealth
{
    /// <summary>
    /// Provider name
    /// </summary>
    public required string Name { get; set; }

    /// <summary>
    /// Whether the provider is operational
    /// </summary>
    public bool IsHealthy { get; set; }

    /// <summary>
    /// Last check performed
    /// </summary>
    public DateTime LastCheck { get; set; }

    /// <summary>
    /// Error messages
    /// </summary>
    public string? ErrorMessage { get; set; }

    /// <summary>
    /// Response time
    /// </summary>
    public TimeSpan? ResponseTime { get; set; }
}
