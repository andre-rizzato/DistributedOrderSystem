namespace NotificationService.Models.Responses;

/// <summary>
/// Base response for notification operations
/// </summary>
public class NotificationResponse
{
    /// <summary>
    /// Whether the operation succeeded
    /// </summary>
    public bool Success { get; set; }

    /// <summary>
    /// ID of the created notification
    /// </summary>
    public long? NotificationId { get; set; }

    /// <summary>
    /// Confirmation or error message
    /// </summary>
    public string? Message { get; set; }

    /// <summary>
    /// External ID from the provider (Twilio SID, etc.)
    /// </summary>
    public string? ExternalId { get; set; }

    /// <summary>
    /// Additional details
    /// </summary>
    public Dictionary<string, string>? Details { get; set; }

    /// <summary>
    /// Timestamp of the operation
    /// </summary>
    public DateTime Timestamp { get; set; } = DateTime.UtcNow;

    /// <summary>
    /// ID of the message generated by the provider
    /// </summary>
    public string? MessageId { get; set; }

    /// <summary>
    /// Notification status
    /// </summary>
    public string? Status { get; set; }

    /// <summary>
    /// Error message (alias for Message)
    /// </summary>
    public string? Error
    {
        get => Success ? null : Message;
        set { if (!Success) Message = value; }
    }

    /// <summary>
    /// Creates an error response
    /// </summary>
    /// <param name="message">Error message</param>
    /// <returns>Response with an error</returns>
    public static NotificationResponse CreateError(string message)
    {
        return new NotificationResponse
        {
            Success = false,
            Message = message,
            Status = "failed"
        };
    }

    /// <summary>
    /// Creates a success response
    /// </summary>
    /// <param name="messageId">Message ID</param>
    /// <param name="message">Confirmation message</param>
    /// <returns>Response indicating success</returns>
    public static NotificationResponse CreateSuccess(string? messageId = null, string? message = null)
    {
        return new NotificationResponse
        {
            Success = true,
            MessageId = messageId,
            Message = message ?? "Notification sent successfully",
            Status = "sent"
        };
    }
}

/// <summary>
/// Response for sending multiple notifications
/// </summary>
public class BulkNotificationResponse
{
    /// <summary>
    /// Total number of requests
    /// </summary>
    public int TotalRequests { get; set; }

    /// <summary>
    /// Total number of notifications processed
    /// </summary>
    public int TotalProcessed { get; set; }

    /// <summary>
    /// Number of notifications sent successfully
    /// </summary>
    public int SuccessCount { get; set; }

    /// <summary>
    /// Number of failed notifications
    /// </summary>
    public int FailureCount { get; set; }

    /// <summary>
    /// Overall success of the operation
    /// </summary>
    public bool Success { get; set; }

    /// <summary>
    /// List of results for each notification in the bulk operation
    /// </summary>
    public List<BulkNotificationResult> Results { get; set; } = new();

    /// <summary>
    /// Total processing time
    /// </summary>
    public TimeSpan ProcessingTime { get; set; }
}

/// <summary>
/// Result for a single notification within a bulk operation
/// </summary>
public class BulkNotificationResult
{
    /// <summary>
    /// Recipient
    /// </summary>
    public required string Recipient { get; set; }

    /// <summary>
    /// Whether the send succeeded
    /// </summary>
    public bool Success { get; set; }

    /// <summary>
    /// Error message (if any)
    /// </summary>
    public string? Error { get; set; }

    /// <summary>
    /// Message ID
    /// </summary>
    public string? MessageId { get; set; }

    /// <summary>
    /// External ID from the provider
    /// </summary>
    public string? ExternalId { get; set; }

    /// <summary>
    /// Notification status
    /// </summary>
    public string? Status { get; set; }
}

/// <summary>
/// Status of a notification
/// </summary>
public class NotificationStatusResponse
{
    /// <summary>
    /// Notification ID
    /// </summary>
    public long NotificationId { get; set; }

    /// <summary>
    /// Current status
    /// </summary>
    public NotificationStatus Status { get; set; }

    /// <summary>
    /// Notification type
    /// </summary>
    public NotificationType Type { get; set; }

    /// <summary>
    /// Recipient
    /// </summary>
    public required string Recipient { get; set; }

    /// <summary>
    /// Subject/title
    /// </summary>
    public required string Subject { get; set; }

    /// <summary>
    /// Creation date
    /// </summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>
    /// Sent date
    /// </summary>
    public DateTime? SentAt { get; set; }

    /// <summary>
    /// Delivered/read date
    /// </summary>
    public DateTime? DeliveredAt { get; set; }

    /// <summary>
    /// Number of attempts
    /// </summary>
    public int RetryCount { get; set; }

    /// <summary>
    /// Last error message
    /// </summary>
    public string? ErrorMessage { get; set; }

    /// <summary>
    /// External provider ID
    /// </summary>
    public string? ExternalId { get; set; }

    /// <summary>
    /// Whether the send completed successfully
    /// </summary>
    public bool Success { get; set; }

    /// <summary>
    /// Last updated date
    /// </summary>
    public DateTime UpdatedAt { get; set; }

    /// <summary>
    /// Error message (if any)
    /// </summary>
    public string? Error { get; set; }
}

