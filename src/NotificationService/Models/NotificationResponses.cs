/// <summary>
/// Response with notification statistics
/// </summary>
public class NotificationStatsResponse
{
    /// <summary>
    /// Statistics by notification type
    /// </summary>
    public Dictionary<NotificationType, TypeStats> TypeStats { get; set; } = new();

    /// <summary>
    /// Statistics by status
    /// </summary>
    public Dictionary<NotificationStatus, int> StatusStats { get; set; } = new();

    /// <summary>
    /// Total notifications in the period
    /// </summary>
    public int TotalNotifications { get; set; }

    /// <summary>
    /// Overall success rate
    /// </summary>
    public double SuccessRate { get; set; }

    /// <summary>
    /// Statistics period
    /// </summary>
    public DateRange Period { get; set; } = new();

    /// <summary>
    /// Average delivery time
    /// </summary>
    public TimeSpan? AverageDeliveryTime { get; set; }
}

